// Generates functions/tracking-ingest/allowlists.js from the sources of truth the browser also uses:
// src/seo/routeRegistry.js (public page paths), src/v4/analytics/campaigns.js (UTM labels) and
// src/v4/analytics/dimensions.js (call to action, location, engagement, form, status, product, destination and experiment values).
//
//   node scripts/appwrite/sync-analytics-allowlists.js          write the file
//   node scripts/appwrite/sync-analytics-allowlists.js --check  exit 1 if the committed file is stale
//
// The Function is deployed from its own directory and cannot import from src/, so it carries a generated copy.
// functions/tracking-ingest/allowlists.test.js fails when the copy is stale, so a route or campaign change cannot
// reach a pull request without it (and the same goes for a new call to action, location, form, product or experiment).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { NOT_FOUND_ANALYTICS_PATH, analyticsPaths } from '../../src/seo/routeRegistry.js';
import { UTM_CAMPAIGNS, UTM_MEDIUMS, UTM_SOURCES } from '../../src/v4/analytics/campaigns.js';
import {
  CTA_IDS,
  CTA_LOCATIONS,
  DESTINATION_LABELS,
  ENGAGEMENT_TYPES,
  EXPERIMENT_VARIANTS,
  FORM_IDS,
  PRODUCT_IDS,
  STATUSES,
} from '../../src/v4/analytics/dimensions.js';

const here = dirname(fileURLToPath(import.meta.url));
export const OUTPUT = resolve(here, '../../functions/tracking-ingest/allowlists.js');

const list = (name, values) => `export const ${name} = ${JSON.stringify([...values].sort(), null, 2)};\n`;
const table = (name, entries) =>
  `export const ${name} = ${JSON.stringify(Object.fromEntries(Object.keys(entries).sort().map((key) => [key, [...entries[key]].sort()])), null, 2)};\n`;

export function renderAllowlists() {
  return [
    '// GENERATED by scripts/appwrite/sync-analytics-allowlists.js. Do not edit by hand.',
    '// Sources: src/seo/routeRegistry.js (analyticsPaths), src/v4/analytics/campaigns.js and src/v4/analytics/dimensions.js.',
    '',
    `export const NOT_FOUND_PATH = ${JSON.stringify(NOT_FOUND_ANALYTICS_PATH)};`,
    '',
    list('KNOWN_PATHS', analyticsPaths()),
    list('UTM_SOURCES', UTM_SOURCES),
    list('UTM_MEDIUMS', UTM_MEDIUMS),
    list('UTM_CAMPAIGNS', UTM_CAMPAIGNS),
    list('CTA_IDS', CTA_IDS),
    list('CTA_LOCATIONS', CTA_LOCATIONS),
    list('ENGAGEMENT_TYPES', ENGAGEMENT_TYPES),
    list('FORM_IDS', FORM_IDS),
    list('STATUSES', STATUSES),
    list('PRODUCT_IDS', PRODUCT_IDS),
    list('DESTINATION_LABELS', DESTINATION_LABELS),
    table('EXPERIMENT_VARIANTS', EXPERIMENT_VARIANTS),
  ].join('\n');
}

function main(argv) {
  const expected = renderAllowlists();
  if (argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUTPUT, 'utf8');
    } catch {
      /* missing counts as stale */
    }
    if (current !== expected) {
      process.stderr.write('functions/tracking-ingest/allowlists.js is stale. Run: node scripts/appwrite/sync-analytics-allowlists.js\n');
      return 1;
    }
    process.stdout.write('allowlists.js is up to date\n');
    return 0;
  }
  writeFileSync(OUTPUT, expected);
  process.stdout.write(`wrote ${OUTPUT}\n`);
  return 0;
}

// Compare resolved file URLs: a relative `node scripts/...` path must still count as the entry point.
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) process.exitCode = main(process.argv.slice(2));
